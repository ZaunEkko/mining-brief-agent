def walk(rng: random.Random, start: float, vol: float, n: int, drift: float = 0.0) -> list[float]:
    values, v = [], start
    for _ in range(n):
        v *= 1 + drift + rng.gauss(0, vol)
        values.append(v)
    return values


def westmetall_page(name: str, days: list[date], prices: list[float]) -> bytes:
    rows = []
    for d, p in sorted(zip(days, prices, strict=True), reverse=True):
        three_month = p * 0.994
        stock = 200_000 + int(p) % 50_000
        rows.append(
            f"<tr>\n<td >{d.day:02d}. {d.strftime('%B %Y')}</td>\n<td >{p:,.2f}</td>\n"
            f'<td >{three_month:,.2f}</td>\n<td class="last">{stock:,}</td>\n</tr>'
        )
    head = (
        '<tr class="shaded"><th class="text">date</th>'
        f'<th class="text">LME {name} Cash-Settlement</th>'
        f'<th class="text">LME {name} 3-month</th><th class="text last">LME {name} stock</th></tr>'
    )
    body = "\n".join(rows)
    return (
        "<!DOCTYPE html><html><head><title>Synthetic demo data</title></head><body>"
        f"<h1>Market data</h1><h2>{name}</h2><!-- SYNTHETIC: generated by "
        f"scripts/make_demo_fixtures.py, not real prices -->\n<table >\n<thead>\n{head} "
        f"</thead>\n<tbody>\n{body}\n</tbody></table></body></html>"
    ).encode()


def sina_payload(days: list[date], prices: list[float]) -> bytes:
    records = []
    for d, p in zip(days, prices, strict=True):
        o, c = p * 0.998, p * 1.002
        records.append(
            {
                "d": d.isoformat(),
                "o": f"{o:.3f}",
                "h": f"{max(o, c) * 1.01:.3f}",
                "l": f"{min(o, c) * 0.99:.3f}",
                "c": f"{c:.3f}",
                "v": str(100000 + int(p) % 90000),
                "p": str(400000 + int(p) % 20000),
                "s": f"{round(p, -1):.3f}",
            }
        )
    return (
        "/*<script>location.href='//sina.com';</script>*/\n/* SYNTHETIC demo data */\n"
        f"var _LC0=({json.dumps(records, separators=(',', ':'))});"
    ).encode()


