def main() -> None:
    if ROOT.exists():
        shutil.rmtree(ROOT)
    store = DiskStore(ROOT / "http")
    manifest: dict[str, dict[str, object]] = {}

    def put(url: str, content: bytes, content_type: str) -> None:
        store.write(url, content, content_type, SNAPSHOT)
        manifest[cache_key(url)] = {
            "url": url,
            "recorded_at": SNAPSHOT.isoformat(),
            "synthetic": True,
        }

    rng = random.Random(20261008)  # noqa: S311 - reproducible demo data, not crypto
    lme_days = trading_days(date(2026, 1, 2), date(2026, 10, 7))
    for commodity, (base, vol) in LME_BASE.items():
        prices = walk(rng, base, vol, len(lme_days))
        put(
            source_for(commodity).url,
            westmetall_page(commodity.value.capitalize(), lme_days, prices),
            "text/html",
        )
    lc_days = trading_days(date(2023, 7, 21), date(2026, 10, 8))
    lc_prices = walk(rng, 220000.0, 0.012, len(lc_days), drift=-0.0006)
    put(
        source_for(Commodity.LITHIUM_CARBONATE).url,
        sina_payload(lc_days, lc_prices),
        "application/javascript",
    )

    project, market = [], []
    for title, age in PROJECT_ITEMS:
        item, url, page = mining_item(title, age, "lithium")
        project.append(item)
        put(url, page, "text/html; charset=utf-8")
    for title, age in MARKET_ITEMS:
        item, url, page = mining_item(title, age, "lithium")
        market.append(item)
        put(url, page, "text/html; charset=utf-8")
    others = [mining_item(t, 1 + i % 9, "general")[0] for i, t in enumerate(OTHER_TOPICS)]

    feeds = search_feed_urls(NEWS_QUERY, 7)
    search_url, commodity_url, front_url, google_url = feeds
    if front_url != MINING_FRONT or google_url != GOOGLE_NEWS.format(query="PLS%20lithium", days=7):
        raise RuntimeError("feed URL layout changed; update make_demo_fixtures.py")
    put(
        search_url,
        rss("You searched for PLS lithium - DEMO", project[:2] + market[:1]),
        "application/rss+xml",
    )
    put(commodity_url, rss("Lithium - DEMO", market + project[2:]), "application/rss+xml")
    put(front_url, rss("DEMO front page", others + market[:2]), "application/rss+xml")
    google = [
        google_item(t, a, i)
        for i, (t, a) in enumerate([*PROJECT_ITEMS, ("PLS Group investor day notes (sample)", 3)])
    ]
    put(google_url, rss('"PLS lithium" - Google News (DEMO)', google), "application/xml")

    put(PROJECTS[0].reports[0].url, resource_pdf(), "application/pdf")

    (ROOT / "MANIFEST.json").write_text(
        json.dumps(
            {
                "_comment": "SYNTHETIC offline dataset; regenerate with scripts/make_demo_fixtures.py",
                **dict(sorted(manifest.items())),
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        "utf-8",
        newline="\n",
    )
    print(f"wrote {len(manifest)} synthetic responses to {ROOT}")


if __name__ == "__main__":
    main()
