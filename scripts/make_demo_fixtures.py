def resource_pdf() -> bytes:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4, invariant=True)  # invariant: reproducible bytes
    pdf.setTitle("SYNTHETIC demo resource statement")
    for lines in PDF_PAGES:
        y = 800
        for line in lines:
            pdf.setFont("Helvetica", 9)
            pdf.drawString(40, y, line)
            y -= 14
        pdf.showPage()
    pdf.save()
    return buffer.getvalue()


